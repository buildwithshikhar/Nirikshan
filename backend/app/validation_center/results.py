"""Read and summarise the committed validation results (docs/validation/results.json).

Location: $NIRIKSHAN_VALIDATION_RESULTS if set, else <repo root>/docs/validation/results.json
(repo root = two levels above the `app` package). A missing or unreadable file is reported as
{"available": false, "reason": ...}; nothing is ever substituted.

Every number returned is a dict carrying `basis`, the data-origin and circularity statement.
"""

from __future__ import annotations

import hashlib
import json
import os
from pathlib import Path

import app as app_pkg
from app.synthetic import ORIGIN_DISCLOSURE, ORIGIN_HEADLINE, TIER_LIMIT
from app.validation import thresholds
from app.validation.score import rate

REPO_ROOT = Path(app_pkg.__file__).resolve().parents[2]
ENV = "NIRIKSHAN_VALIDATION_RESULTS"
BASIS = (
    f"{ORIGIN_HEADLINE}. {ORIGIN_DISCLOSURE} Measured on images generated by Nirikshan's own "
    "validation harness; parsers built from a published layout and tested on images generated "
    "from that same layout are a circular check, not independent validation. "
    f"{TIER_LIMIT}"
)
VENDOR_ENGINES = {
    "Generic carver": ("generic",),
    "Dahua": ("dahua", "dahua+generic"),
    "Hikvision": ("hikvision", "hikvision+generic"),
    "Honeywell": ("honeywell", "honeywell+generic"),
}


def results_path() -> Path:
    env = os.getenv(ENV, "").strip()
    return (
        Path(env).expanduser().resolve()
        if env
        else REPO_ROOT / "docs" / "validation" / "results.json"
    )


def sha256_file(p: Path) -> str | None:
    try:
        return hashlib.sha256(p.read_bytes()).hexdigest()
    except OSError:
        return None


def load(path: Path | None = None) -> tuple[dict | None, dict]:
    """(results, info). results is None when unavailable; info then has the reason."""
    p = path or results_path()
    info: dict = {"path": str(p)}
    try:
        raw = p.read_bytes()
    except OSError as e:
        return None, {
            **info,
            "available": False,
            "reason": f"validation results not found at {p} ({type(e).__name__}); run "
            f"`make validate` or set {ENV}",
        }
    try:
        res = json.loads(raw)
        assert isinstance(res.get("scenarios"), list)
    except (ValueError, AssertionError, AttributeError):
        return None, {**info, "available": False, "reason": f"{p} is not a validation result file"}
    from app.validation.run import digest

    recomputed = digest(res)
    info.update(
        available=True,
        file_sha256=hashlib.sha256(raw).hexdigest(),
        results_digest=res.get("results_digest"),
        digest_recomputed=recomputed,
        digest_verified=recomputed == res.get("results_digest"),
    )
    return res, info


def num(m: dict | None, **extra) -> dict | None:
    """A metric as {k, n, rate, ci95, basis}."""
    if m is None:
        return None
    return {**m, **extra, "basis": BASIS}


def summary(res: dict, info: dict) -> dict:
    sc = res["scenarios"]
    return {
        **info,
        "headline": ORIGIN_HEADLINE,
        "disclosure": ORIGIN_DISCLOSURE,
        "tier_limit": TIER_LIMIT,
        "basis": BASIS,
        "disclaimer": res.get("disclaimer", []),
        "synthetic": res.get("synthetic"),
        "seed": res.get("seed"),
        "trials": res.get("trials"),
        "engine": res.get("engine"),
        "export_decode_test": res.get("export_decode_test"),
        "tool_version": res.get("tool_version"),
        "ffmpeg": res.get("ffmpeg"),
        "scenario_results": {"count": len(sc), "basis": BASIS},
        "scenario_definitions": len({s["scenario"] for s in sc}),
        "engines": sorted({s["engine"] for s in sc}),
        "stored_threshold_violations": (res.get("thresholds") or {}).get("violations"),
    }


def _tiers() -> dict[str, str]:
    from app.vendors import default_registry

    return {p.vendor: p.tier for p in default_registry().parsers}


def _pooled(rows: list[dict], metric: str) -> dict | None:
    ms = [s["metrics"].get(metric) for s in rows if s["kind"] == "positive"]
    ms = [m for m in ms if m and m.get("n")]
    if not ms:
        return None
    k, n = sum(m["k"] for m in ms), sum(m["n"] for m in ms)
    return num(
        rate(k, n),
        pooled_over=len(ms),
        note="sum of k and n over scenarios of different difficulty; descriptive only",
    )


def scorecards(res: dict) -> list[dict]:
    tiers = _tiers()
    cards = []
    for vendor, engines in VENDOR_ENGINES.items():
        rows = [s for s in res["scenarios"] if s["engine"] in engines]
        tier = tiers.get(vendor, "n/a (format-agnostic carver, no vendor structures)")
        per_engine = []
        for eng in engines:
            er = [s for s in rows if s["engine"] == eng]
            per_engine.append(
                {
                    "engine": eng,
                    "scenarios": [
                        {
                            "id": s["id"],
                            "scenario": s["scenario"],
                            "title": s.get("title"),
                            "kind": s["kind"],
                            "layout": s.get("layout"),
                            "trials": s["trials"],
                            "recall": num(s["metrics"].get("clip_recall")),
                            "precision": num(s["metrics"].get("clip_precision")),
                            "frame_recall": num(s["metrics"].get("frame_recall")),
                            "byte_exact": num(s["metrics"].get("byte_exact")),
                            "decode_ok": num(s["metrics"].get("decode_ok")),
                        }
                        for s in er
                    ],
                    "pooled_recall": _pooled(er, "clip_recall"),
                    "pooled_precision": _pooled(er, "clip_precision"),
                }
            )
        cards.append(
            {
                "vendor": vendor,
                "tier": tier,
                "scenario_results": len(rows),
                "engines": per_engine,
                "basis": BASIS,
            }
        )
    return cards


def regression(res: dict) -> dict:
    full = res.get("engine") == "all"
    t = thresholds.load()
    viol = thresholds.check(res, t, require_present=full)
    by_id = {s["id"]: s for s in res["scenarios"]}
    rules = []
    for sid, metrics in t.items():
        for metric, rule in metrics.items():
            m = (by_id.get(sid) or {}).get("metrics", {}).get(metric)
            failed = [
                v for v in viol if v.startswith(f"{sid}.{metric}:") or v.startswith(f"{sid}:")
            ]
            rules.append(
                {
                    "scenario": sid,
                    "metric": metric,
                    "rule": rule,
                    "observed": num(m),
                    "pass": not failed,
                    "violations": failed,
                }
            )
    stored = (res.get("thresholds") or {}).get("violations")
    return {
        "status": "pass" if not viol else "fail",
        "violations": viol,
        "stored_violations": stored,
        "stored_matches_recomputed": stored == viol if stored is not None else None,
        "thresholds_file": "app/validation/thresholds.json",
        "require_present": full,
        "rules": rules,
        "basis": BASIS,
    }


def false_rates(res: dict) -> dict:
    neg, fa, fp = [], [], []
    for s in res["scenarios"]:
        m, c = s["metrics"], s.get("counts", {})
        if s["kind"] == "negative":
            neg.append(
                {
                    "id": s["id"],
                    "engine": s["engine"],
                    "title": s.get("title"),
                    "images": s["trials"],
                    "clips_emitted": num(m.get("clips_emitted")),
                    "false_accept_decodable_clips": num(m.get("clips_decoded_ok")),
                    "emitted_but_flagged_failed": num(m.get("emitted_but_flagged_failed")),
                }
            )
            continue
        if "reassembler_false_accept" in m:
            fa.append(
                {
                    "id": s["id"],
                    "engine": s["engine"],
                    "reassembler_false_accept": num(m["reassembler_false_accept"]),
                    "reassembler_true_accept": num(m.get("reassembler_true_accept")),
                }
            )
        if c.get("carved"):
            fp.append(
                {
                    "id": s["id"],
                    "engine": s["engine"],
                    "false_positive_clips": num(
                        rate(c["carved"] - c.get("tp", 0), c["carved"]),
                        derived="(carved - true positives) / carved",
                    ),
                    "mixed_clips": num(m.get("mixed_clips")),
                }
            )
    return {
        "negative_scenarios": neg,
        "reassembler": fa,
        "positive_scenario_false_positives": fp,
        "notes": [
            "Negative scenarios contain no valid video; a decodable clip there is a false accept.",
            "The fragment reassembler is off by default; its rates are measured with it on.",
        ],
        "basis": BASIS,
    }


def crosscheck(res: dict) -> dict:
    from app.validation.run import BENIGN

    rows, totals = [], {}
    for s in res["scenarios"]:
        if s["engine"] == "generic":
            continue
        kinds = s.get("crosscheck_disagreements") or {}
        vendor = s["engine"].split("+")[0]
        t = totals.setdefault(vendor, {})
        for k, v in kinds.items():
            t[k] = t.get(k, 0) + v
        rows.append(
            {
                "id": s["id"],
                "engine": s["engine"],
                "images": s["trials"],
                "disagreement_kinds": kinds,
                "benign_kinds": sorted(k for k in kinds if k in BENIGN),
                "non_benign_disagreement_images": num(
                    s["metrics"].get("crosscheck_disagreement_images")
                ),
            }
        )
    return {
        "scenarios": rows,
        "totals_by_vendor": {
            v: {k: {"count": n, "basis": BASIS} for k, n in kinds.items()}
            for v, kinds in sorted(totals.items())
        },
        "benign_definition": sorted(BENIGN),
        "explanation": (
            "Parser output is compared with the generic carver on the same image. Kinds listed as "
            "benign are expected header absorption by the generic carver; the per-scenario rate "
            "counts images with at least one non-benign disagreement."
        ),
        "basis": BASIS,
    }
